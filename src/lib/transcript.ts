/**
 * Transcripts for the watch screen: reading a YouTube link, turning caption
 * fragments into sentences, reading uploaded subtitle files, and splitting a
 * line into clickable words. Pure: no network, no database.
 */

/** One sentence (or so) of a transcript. `start` is in seconds. */
export interface TranscriptLine {
  start: number;
  text: string;
}

/** A caption fragment as a source hands it over. Seconds. */
export interface CaptionSegment {
  start: number;
  duration: number;
  text: string;
}

/** A caption track a video offers. */
export interface CaptionTrack {
  lang: string;
  name: string;
  /** Auto-generated by YouTube's speech recognition, rather than written by a person. */
  auto: boolean;
}

const VIDEO_ID = /^[A-Za-z0-9_-]{11}$/;

/**
 * The 11-character video id from whatever was pasted: a bare id, a watch link,
 * a youtu.be short link, or a shorts, embed or live link. Null when there is
 * no id in it.
 */
export function parseVideoId(input: string): string | null {
  const value = input.trim();
  if (VIDEO_ID.test(value)) return value;

  let url: URL;
  try {
    url = new URL(/^https?:\/\//i.test(value) ? value : `https://${value}`);
  } catch {
    return null;
  }

  const host = url.hostname.toLowerCase().replace(/^(www|m|music)\./, "");
  let candidate: string | null = null;
  if (host === "youtu.be") {
    candidate = url.pathname.split("/")[1] ?? null;
  } else if (host === "youtube.com" || host === "youtube-nocookie.com") {
    const [, first, second] = url.pathname.split("/");
    if (first === "watch") candidate = url.searchParams.get("v");
    else if (["shorts", "embed", "live", "v"].includes(first)) candidate = second ?? null;
  }
  return candidate && VIDEO_ID.test(candidate) ? candidate : null;
}

/** A start time in seconds from a link's `t` or `start` parameter: "90", "90s", "1m30s". */
export function parseStartTime(input: string | null | undefined): number {
  if (!input) return 0;
  const value = input.trim();
  if (/^\d+(\.\d+)?s?$/.test(value)) return Math.floor(Number.parseFloat(value));
  const match = /^(?:(\d+)h)?(?:(\d+)m)?(?:(\d+)s)?$/.exec(value);
  if (!match || value === "") return 0;
  const [, h = "0", m = "0", s = "0"] = match;
  return Number(h) * 3600 + Number(m) * 60 + Number(s);
}

/** "0:07", "12:30", "1:02:03". */
export function formatTimestamp(seconds: number): string {
  const total = Math.max(0, Math.floor(seconds));
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = String(total % 60).padStart(2, "0");
  return h > 0 ? `${h}:${String(m).padStart(2, "0")}:${s}` : `${m}:${s}`;
}

const NAMED_ENTITIES: Record<string, string> = {
  amp: "&",
  lt: "<",
  gt: ">",
  quot: '"',
  apos: "'",
  nbsp: " ",
};

function decodeOnce(text: string): string {
  return text.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (whole, code: string) => {
    if (code[0] === "#") {
      const point =
        code[1] === "x" || code[1] === "X"
          ? Number.parseInt(code.slice(2), 16)
          : Number.parseInt(code.slice(1), 10);
      return Number.isFinite(point) && point > 0 && point <= 0x10ffff ? String.fromCodePoint(point) : whole;
    }
    return NAMED_ENTITIES[code.toLowerCase()] ?? whole;
  });
}

/**
 * Turn HTML entities back into characters. YouTube's caption XML encodes them
 * twice ("&amp;#39;" for an apostrophe), so this runs until nothing changes.
 */
export function decodeEntities(text: string): string {
  let current = text;
  for (let pass = 0; pass < 3; pass += 1) {
    const next = decodeOnce(current);
    if (next === current) break;
    current = next;
  }
  return current;
}

/** Strip markup and squeeze whitespace, so a fragment reads as plain text. */
function cleanText(text: string): string {
  return decodeEntities(text.replace(/<[^>]*>/g, ""))
    .replace(/\s+/g, " ")
    .trim();
}

/** The `<text start dur>` elements of YouTube's caption XML. */
export function parseTimedTextXml(xml: string): CaptionSegment[] {
  const segments: CaptionSegment[] = [];
  const pattern = /<text\b([^>]*)>([\s\S]*?)<\/text>/g;
  for (const match of xml.matchAll(pattern)) {
    const attributes = match[1];
    const start = Number(/\bstart="([\d.]+)"/.exec(attributes)?.[1]);
    const duration = Number(/\bdur="([\d.]+)"/.exec(attributes)?.[1] ?? 0);
    if (!Number.isFinite(start)) continue;
    segments.push({ start, duration: Number.isFinite(duration) ? duration : 0, text: match[2] });
  }
  return segments;
}

/** "[Music]", "(applause)", "♪♪♪": sound cues, kept on a line of their own. */
function isSoundCue(text: string): boolean {
  return /^[[(].*[\])]$/.test(text) || /^[♪\s]+$/.test(text);
}

const SENTENCE_END = /[.!?…]["'”’)\]]*$/;
/** A pause this long between words starts a new line even mid-sentence. */
const PAUSE_SECONDS = 2.5;
const MAX_WORDS = 40;
const MIN_WORDS = 2;

type TimedWord = { time: number; text: string };

/** Lines from timed words: break after a sentence ends, on a long pause, or when a line runs long. */
function groupWords(words: TimedWord[], useSentences: boolean): TranscriptLine[] {
  const lines: TranscriptLine[] = [];
  let current: TimedWord[] = [];

  const flush = () => {
    if (current.length > 0) {
      lines.push({ start: current[0].time, text: current.map((word) => word.text).join(" ") });
    }
    current = [];
  };

  for (const word of words) {
    const last = current.at(-1);
    if (last && word.time - last.time > PAUSE_SECONDS) flush();
    current.push(word);
    const ends = useSentences && SENTENCE_END.test(word.text) && current.length >= MIN_WORDS;
    if (ends || current.length >= MAX_WORDS) flush();
  }
  flush();
  return lines;
}

/**
 * Caption fragments into sentence lines.
 *
 * Fragments break wherever the captioner's screen ran out, so "We're no
 * strangers to" / "love. You know the rules" is common. When the captions are
 * punctuated, every word gets a time (spread evenly across its fragment) and
 * lines break at sentence ends instead. Unpunctuated captions keep their
 * fragments as lines, since there is no better boundary to go by. Either way a
 * sentence is what ends up on a flashcard as the example.
 */
export function linesFromSegments(segments: CaptionSegment[]): TranscriptLine[] {
  const sorted = segments
    .map((segment) => ({ ...segment, text: cleanText(segment.text) }))
    .filter((segment) => segment.text !== "")
    .sort((a, b) => a.start - b.start);

  const totalWords = sorted.reduce((sum, segment) => sum + segment.text.split(" ").length, 0);
  const sentenceMarks = sorted.reduce(
    (sum, segment) => sum + (segment.text.match(/[.!?…](\s|$)/g)?.length ?? 0),
    0,
  );
  const punctuated = totalWords > 0 && sentenceMarks * 40 >= totalWords;

  if (!punctuated) {
    return sorted.map((segment) => ({ start: segment.start, text: segment.text }));
  }

  const lines: TranscriptLine[] = [];
  let words: TimedWord[] = [];
  sorted.forEach((segment, index) => {
    if (isSoundCue(segment.text)) {
      lines.push(...groupWords(words, true));
      words = [];
      lines.push({ start: segment.start, text: segment.text });
      return;
    }
    const next = sorted[index + 1];
    const span = Math.max(
      0,
      Math.min(segment.duration || 0, next ? next.start - segment.start : segment.duration || 0),
    );
    const parts = segment.text.split(" ");
    parts.forEach((text, i) => {
      words.push({ time: segment.start + (span * i) / parts.length, text });
    });
  });
  lines.push(...groupWords(words, true));
  return lines.sort((a, b) => a.start - b.start);
}

/** Plain text with no timings: one line per sentence. */
export function linesFromPlainText(text: string): TranscriptLine[] {
  const words = cleanText(text)
    .split(" ")
    .filter(Boolean)
    .map((word) => ({ time: 0, text: word }));
  return groupWords(words, true);
}

const CUE_TIME = /(?:(\d+):)?(\d{1,2}):(\d{2})[.,](\d{1,3})/;

function cueSeconds(stamp: string): number | null {
  const match = CUE_TIME.exec(stamp);
  if (!match) return null;
  const [, h = "0", m, s, fraction] = match;
  return Number(h) * 3600 + Number(m) * 60 + Number(s) + Number(fraction.padEnd(3, "0")) / 1000;
}

export interface ParsedSubtitles {
  lines: TranscriptLine[];
  /** False for plain text, which has no times to follow the video by. */
  timed: boolean;
}

/**
 * An uploaded or pasted transcript: SRT, WebVTT, or plain text.
 *
 * Cues are found by their "00:00:01,000 --> 00:00:03,500" line, which SRT and
 * VTT share. Inline tags are dropped, and a line repeated from the cue before is
 * skipped -- YouTube's own auto-caption VTT rolls each line up into the next cue.
 */
export function parseSubtitleFile(raw: string): ParsedSubtitles {
  const text = raw.replace(/^﻿/, "").replace(/\r\n?/g, "\n");
  if (!/-->/.test(text)) {
    return { lines: linesFromPlainText(text), timed: false };
  }

  const segments: CaptionSegment[] = [];
  let lastLine = "";
  for (const block of text.split(/\n{2,}/)) {
    const rows = block.split("\n");
    const timingIndex = rows.findIndex((row) => row.includes("-->"));
    if (timingIndex === -1) continue;
    const [from, to] = rows[timingIndex].split("-->");
    const start = cueSeconds(from);
    const end = cueSeconds(to ?? "");
    if (start === null) continue;

    const fresh: string[] = [];
    for (const row of rows.slice(timingIndex + 1)) {
      const line = cleanText(row);
      if (line === "" || line === lastLine) continue;
      fresh.push(line);
      lastLine = line;
    }
    if (fresh.length === 0) continue;
    segments.push({
      start,
      duration: end !== null && end > start ? end - start : 0,
      text: fresh.join(" "),
    });
  }
  return { lines: linesFromSegments(segments), timed: true };
}

/** A piece of a line: a word you can click, or the spaces and punctuation between. */
export interface Token {
  text: string;
  /** The word to look up, lowercased. Null for anything that is not a word. */
  word: string | null;
}

const WORD = /\p{L}+(?:['’]\p{L}+)*/gu;

/** Split a line into words and the bits between them, keeping every character. */
export function tokenize(text: string): Token[] {
  const tokens: Token[] = [];
  let index = 0;
  for (const match of text.matchAll(WORD)) {
    const at = match.index ?? 0;
    if (at > index) tokens.push({ text: text.slice(index, at), word: null });
    tokens.push({ text: match[0], word: normalizeWord(match[0]) });
    index = at + match[0].length;
  }
  if (index < text.length) tokens.push({ text: text.slice(index), word: null });
  return tokens;
}

/** Lowercase, straight apostrophes, no surrounding punctuation. */
export function normalizeWord(word: string): string {
  return word
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/^[^\p{L}]+|[^\p{L}]+$/gu, "");
}

/** The index of the line playing at `time`: the last one that has started. -1 before the first. */
export function activeLineIndex(lines: readonly TranscriptLine[], time: number): number {
  let low = 0;
  let high = lines.length - 1;
  let found = -1;
  while (low <= high) {
    const middle = (low + high) >> 1;
    if (lines[middle].start <= time) {
      found = middle;
      low = middle + 1;
    } else {
      high = middle - 1;
    }
  }
  return found;
}

function baseLang(lang: string): string {
  return lang.toLowerCase().split(/[-_]/)[0];
}

/**
 * Which caption track to show: English, then anything. Captions a person
 * wrote beat auto-generated ones.
 */
export function pickTrack<T extends CaptionTrack>(tracks: readonly T[]): T | null {
  if (tracks.length === 0) return null;
  const english = tracks.filter((track) => baseLang(track.lang) === "en");
  const best = (list: readonly T[]) => [...list].sort((a, b) => Number(a.auto) - Number(b.auto))[0] ?? null;
  return best(english) ?? best(tracks);
}
